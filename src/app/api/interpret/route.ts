// ─── Layer 3 + D-chart user message ──────────────────────────────────────────

function buildDchartUserMessage(section: DchartSection, dataStr: string): string {
  const disciplineDeclaration =
    'This is a Sidereal Lahiri Jyotish section. ' +
    'There is no Human Design data in this payload. ' +
    'Do not reference gates, channels, centers, Incarnation Cross, type, profile, ' +
    'authority, variables, or any Human Design mechanic anywhere in this section. ' +
    'Do not reference Gene Keys, Shadow, Gift, Siddhi, or any Gene Keys language ' +
    'anywhere in this section. ' +
    'Interpret using classical Jyotish mechanics only.\n\n'

  return (
    disciplineDeclaration +
    `Here is the complete chart data:\n\n${dataStr}\n\n` +
    `Interpret ${section.name} only. ` +
    `The D${section.n} placements are in divisional_chart; the natal (D1) chart is context only. ` +
    `Read only the chart data fields directly relevant to ${section.name}. ` +
    `Do not bring in planetary placements or house themes that belong to other sections.` +
    ` Speak directly to this person in second person, present tense. ` +
    `No bullet points. No markdown. No asterisks. No em dashes. ` +
    `No hedging language. No textbook definitions. ` +
    SELF_REVIEW + ' ' +
    `Write up to ${section.wordCap} words. Do not exceed ${section.wordCap} words.`
  )
}

// ─── Route ────────────────────────────────────────────────────────────────────

export async function POST(request: NextRequest) {
  const supabase = await createClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return jsonError('Unauthorized', 401)

  const body    = await request.json().catch(() => ({})) as { chart_id?: unknown; product?: unknown }
  const product = PRODUCTS[String(body.product) as keyof typeof PRODUCTS]
  if (!product) return jsonError('product must be natal, dcharts or combined', 400)
  if (typeof body.chart_id !== 'string' || !body.chart_id) return jsonError('chart_id required', 400)

  if (!(await hasEntitlement(supabase, user.id, [...product.entitlements]))) return jsonError('Not purchased', 403)

  const chart = await loadOwnedChart(supabase, user.id, { id: body.chart_id })
  if (!chart) return jsonError('Chart not found', 404)
  const birth = birthFromChartJson(chart.chart_json)
  if (!birth) return jsonError('Chart has no usable birth data', 422)
  const intake = (chart.intake_self as Record<string, unknown> | null) ?? null

  const offered = [
    ...(product.natal   ? NATAL_COLUMNS : []),
    ...(product.dcharts ? DCHART_SECTIONS.map(s => s.column) : []),
  ]
  const missing = offered.filter(c => isMissing(chart[c]))
  const skipped = offered.filter(c => !missing.includes(c))
  const dchartByColumn = new Map(DCHART_SECTIONS.map(s => [s.column, s]))
  const admin = createAdminClient()

  // D-chart context is assembled once, on first use, and only when a D-chart
  // section is actually pending. Any failure here fails every D-chart section.
  let dchartContext: Promise<{ system: string; payload: Record<string, unknown>; dcharts: Record<string, unknown> }> | null = null
  const getDchartContext = () => dchartContext ??= (async () => {
    const [systemDoc, coreDoc, astroDoc, dcharts, conclusions] = await Promise.all([
      fetchGoverningDoc('CLAUDE_SYSTEM.md'),
      fetchGoverningDoc('CLAUDE_CORE_DCHARTS.md'),
      fetchGoverningDoc('CLAUDE_ASTRO.md'),
      fetchCalculation('/astrology/dcharts', birth),
      fetchDomainConclusions(birth as never, 'self', intake, true),
    ])
    const configured = configureSystemDoc(systemDoc, {
      product:       'dcharts',
      personA:       'natal and divisional_chart',
      intake:        !!intake,
      conclusions:   !!conclusions,
      classicalOnly: true,
    })
    const payload: Record<string, unknown> = { ...buildAstrologyPayload(chart.chart_json) }
    if (intake)      payload.intake = intake
    // Astrology-only product: no HD or Gene Keys signals in the conclusions.
    if (conclusions) payload.domain_conclusions = jyotishOnlyConclusions(conclusions)
    return { system: [configured, coreDoc, astroDoc].join('\n\n---\n\n'), payload, dcharts }
  })()

  const anthropic = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY })

  return sectionStream('interpret', missing, skipped, async column => {
    const dsec = dchartByColumn.get(column)
    if (!dsec) {
      const result = await callBackendInterpret('/interpret/natal', { birth, section: column, intake })
      await writeSection(admin, String(chart.id), column, result.text)
      return result
    }
    const ctx = await getDchartContext()
    const divisional = ctx.dcharts[String(dsec.n)]
    if (!divisional) throw new InterpretFailure(`D${dsec.n} not returned by calculation`, 502)
    const dataStr = JSON.stringify({ ...ctx.payload, divisional_chart: { chart: `D${dsec.n}`, data: divisional } }, null, 2)
    const result = await generateDirect({
      anthropic,
      system:  ctx.system,
      user:    buildDchartUserMessage(dsec, dataStr),
      section: column,
      product: 'dcharts',
    })
    await writeSection(admin, String(chart.id), column, result.text)
    return result
  })
}
